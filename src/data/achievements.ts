export interface AchievementDef {
  id: string;
  title: string;
  desc: string;
  icon: string;
  category: AchievementCategory;
  rarity: Rarity;
  target: number;
  /** Nåværende fremdrift, regnet ut fra statistikken alene. */
  metric: (stats: PlayerStats) => number;
  /** Bonus-XP når den låses opp. */
  xp: number;
  /** Gir også et emblem som vises på profilen. */
  emblem?: boolean;
}

const nonNeg = (n: number) => Math.max(0, n);

/** Dager mellom første og siste fullførte runde. */
const spanDays = (s: PlayerStats): number =>
  s.extras.firstPlayAt > 0
    ? Math.floor((s.extras.lastPlayAt - s.extras.firstPlayAt) / 86_400_000)
    : 0;

/** Spandager teller bare hvis man faktisk har spilt jevnlig (minst `rounds` runder). */
const steadySpan = (rounds: number) => (s: PlayerStats): number =>
  allTotals(s).rounds >= rounds ? spanDays(s) : 0;

const putts = (s: PlayerStats): number => s.modes.putter.putts;

/** Antall ulike værtyper man har spilt i (regn, kraftig regn, vind, storm, sol, varme, kulde). */
const weatherVariety = (s: PlayerStats): number =>
  [
    s.extras.rainRounds,
    s.extras.heavyRainRounds,
    s.extras.windRounds,
    s.extras.stormRounds,
    s.extras.sunRounds,
    s.extras.hotRounds,
    s.extras.coldRounds,
  ].filter((n) => n > 0).length;

/** Hvor mange disktyper (på hjulet) man har fått par eller bedre med. */
const rouletteTypesCleared = (s: PlayerStats): number =>
  ROULETTE_SEGMENTS.filter((seg) => seg.discType).filter((seg) => {
    const o = s.modes.roulette.byOutcome[seg.id];
    return o ? parOrBetter(o.counts) > 0 : false;
  }).length;

